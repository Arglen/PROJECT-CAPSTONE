package com.example.system_mini_capstone.admin.analytics

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.RectF
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Automates the generation of structured, professional PDF administrative usage reports
 * using Android's native PdfDocument engine.
 */
object PdfReportGenerator {

    private const val PAGE_WIDTH = 595  // Standard A4 width in points (72 dpi)
    private const val PAGE_HEIGHT = 842 // Standard A4 height in points (72 dpi)
    private const val MARGIN = 40f

    suspend fun generateReport(
        context: Context,
        adminEmail: String,
        metrics: GlobalMetrics,
        topLessons: List<LessonPerformance>,
        lowLessons: List<LessonPerformance>,
        weeklyStats: List<DailyActivityStat>
    ): File = withContext(Dispatchers.IO) {
        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, 1).create()
        val page = document.startPage(pageInfo)
        val canvas: Canvas = page.canvas

        drawReportContent(
            canvas = canvas,
            adminEmail = adminEmail,
            metrics = metrics,
            topLessons = topLessons,
            lowLessons = lowLessons,
            weeklyStats = weeklyStats
        )

        document.finishPage(page)

        // Write PDF to cache reports directory
        val reportsDir = File(context.cacheDir, "reports").apply { if (!exists()) mkdirs() }
        val timeStamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US).format(Date())
        val outputFile = File(reportsDir, "SignLink_Usage_Report_$timeStamp.pdf")

        FileOutputStream(outputFile).use { out ->
            document.writeTo(out)
        }
        document.close()

        outputFile
    }

    private fun drawReportContent(
        canvas: Canvas,
        adminEmail: String,
        metrics: GlobalMetrics,
        topLessons: List<LessonPerformance>,
        lowLessons: List<LessonPerformance>,
        weeklyStats: List<DailyActivityStat>
    ) {
        val textPaint = Paint(Paint.ANTI_ALIAS_FLAG)
        val rectPaint = Paint(Paint.ANTI_ALIAS_FLAG)

        // 1. Header Banner
        rectPaint.color = Color.rgb(26, 82, 118) // Deep Blue Accent
        canvas.drawRect(0f, 0f, PAGE_WIDTH.toFloat(), 90f, rectPaint)

        textPaint.color = Color.WHITE
        textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        textPaint.textSize = 18f
        canvas.drawText("SignLink Administrative Usage & Analytics Report", MARGIN, 42f, textPaint)

        textPaint.textSize = 10f
        textPaint.typeface = Typeface.DEFAULT
        val currentDate = SimpleDateFormat("MMMM dd, yyyy - HH:mm:ss z", Locale.US).format(Date())
        canvas.drawText("Generated by: $adminEmail  |  Date: $currentDate", MARGIN, 68f, textPaint)

        var y = 115f

        // 2. Section: Global App Usage & Telemetry KPI Grid
        textPaint.color = Color.rgb(33, 33, 33)
        textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        textPaint.textSize = 13f
        canvas.drawText("1. Global Usage Telemetry & Active Sessions", MARGIN, y, textPaint)
        y += 16f

        // Draw 3 Metric Cards side by side
        val cardWidth = (PAGE_WIDTH - (MARGIN * 2) - 20f) / 3f
        drawMetricCard(canvas, MARGIN, y, cardWidth, 52f, "Active Sessions", "${metrics.activeSessions}", "Live connected")
        drawMetricCard(canvas, MARGIN + cardWidth + 10f, y, cardWidth, 52f, "Translations Today", "${metrics.totalTranslationsToday}", "Frames analyzed")
        drawMetricCard(canvas, MARGIN + (cardWidth * 2) + 20f, y, cardWidth, 52f, "Accuracy / Latency", "${metrics.avgAccuracyScore}%", "${metrics.avgInferenceLatencyMs} ms inference")
        y += 72f

        // 3. Section: Top-Performing Content Table
        textPaint.color = Color.rgb(33, 33, 33)
        textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        textPaint.textSize = 13f
        canvas.drawText("2. Top-Performing Sign Content (Highest Success & Completion)", MARGIN, y, textPaint)
        y += 18f

        // Table Header
        drawTableHeader(canvas, y, listOf("Sign / Gesture Name", "Category", "Attempts", "Success %", "Completion %"))
        y += 20f

        textPaint.typeface = Typeface.DEFAULT
        textPaint.textSize = 9.5f
        textPaint.color = Color.rgb(40, 40, 40)

        for (item in topLessons) {
            drawTableRow(
                canvas = canvas,
                y = y,
                columns = listOf(item.signName, item.category, "${item.totalAttempts}", "${item.successRate}%", "${item.completionRate}%"),
                isHighlight = false
            )
            y += 16f
        }
        y += 16f

        // 4. Section: Low-Performing Content (Requires Curriculum / Model Retraining)
        textPaint.color = Color.rgb(180, 40, 40)
        textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        textPaint.textSize = 13f
        canvas.drawText("3. Low-Performing Content (Review & Model Retraining Alert)", MARGIN, y, textPaint)
        y += 18f

        drawTableHeader(canvas, y, listOf("Flagged Sign Name", "Category", "Attempts", "Accuracy %", "Status Alert"), isAlert = true)
        y += 20f

        textPaint.typeface = Typeface.DEFAULT
        textPaint.textSize = 9.5f

        for (item in lowLessons) {
            drawTableRow(
                canvas = canvas,
                y = y,
                columns = listOf(item.signName, item.category, "${item.totalAttempts}", "${item.successRate}%", "Review Required"),
                isHighlight = true
            )
            y += 16f
        }
        y += 20f

        // 5. Section: Weekly Session Volume Summary
        textPaint.color = Color.rgb(33, 33, 33)
        textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        textPaint.textSize = 13f
        canvas.drawText("4. 7-Day Session & Translation Volume Breakdown", MARGIN, y, textPaint)
        y += 18f

        drawTableHeader(canvas, y, listOf("Day", "Sessions Count", "Translations Generated", "Daily Avg", "Status"))
        y += 20f

        textPaint.typeface = Typeface.DEFAULT
        textPaint.textSize = 9.5f

        for (day in weeklyStats) {
            val avg = day.translationCount / day.sessionCount
            drawTableRow(
                canvas = canvas,
                y = y,
                columns = listOf(day.dayOfWeek, "${day.sessionCount}", "${day.translationCount}", "$avg / session", "Normal"),
                isHighlight = false
            )
            y += 15f
        }

        // 6. Footer
        val footerPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.GRAY
            textSize = 9f
            textAlign = Paint.Align.CENTER
        }
        canvas.drawLine(MARGIN, PAGE_HEIGHT - 35f, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 35f, footerPaint)
        canvas.drawText("CONFIDENTIAL - SignLink Mobile Computer Vision & Sign Language Translation Administrative System  |  Page 1 of 1", PAGE_WIDTH / 2f, PAGE_HEIGHT - 20f, footerPaint)
    }

    private fun drawMetricCard(
        canvas: Canvas,
        x: Float,
        y: Float,
        width: Float,
        height: Float,
        title: String,
        value: String,
        subtitle: String
    ) {
        val rectPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(245, 247, 250)
        }
        canvas.drawRoundRect(RectF(x, y, x + width, y + height), 6f, 6f, rectPaint)

        val borderPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(220, 224, 230)
            style = Paint.Style.STROKE
            strokeWidth = 1f
        }
        canvas.drawRoundRect(RectF(x, y, x + width, y + height), 6f, 6f, borderPaint)

        val paint = Paint(Paint.ANTI_ALIAS_FLAG)
        paint.color = Color.DKGRAY
        paint.textSize = 9f
        canvas.drawText(title, x + 10f, y + 16f, paint)

        paint.color = Color.rgb(26, 82, 118)
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 14f
        canvas.drawText(value, x + 10f, y + 33f, paint)

        paint.color = Color.GRAY
        paint.typeface = Typeface.DEFAULT
        paint.textSize = 8f
        canvas.drawText(subtitle, x + 10f, y + 46f, paint)
    }

    private fun drawTableHeader(
        canvas: Canvas,
        y: Float,
        headers: List<String>,
        isAlert: Boolean = false
    ) {
        val bgPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = if (isAlert) Color.rgb(254, 237, 236) else Color.rgb(235, 240, 245)
        }
        canvas.drawRect(MARGIN, y - 12f, PAGE_WIDTH - MARGIN, y + 6f, bgPaint)

        val textPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = if (isAlert) Color.rgb(180, 40, 40) else Color.rgb(30, 60, 90)
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            textSize = 9f
        }

        val colWidth = (PAGE_WIDTH - (MARGIN * 2)) / headers.size
        headers.forEachIndexed { index, header ->
            canvas.drawText(header, MARGIN + (index * colWidth) + 4f, y, textPaint)
        }
    }

    private fun drawTableRow(
        canvas: Canvas,
        y: Float,
        columns: List<String>,
        isHighlight: Boolean
    ) {
        val textPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = if (isHighlight) Color.rgb(180, 40, 40) else Color.rgb(40, 40, 40)
            textSize = 9f
            if (isHighlight) typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val colWidth = (PAGE_WIDTH - (MARGIN * 2)) / columns.size
        columns.forEachIndexed { index, col ->
            canvas.drawText(col, MARGIN + (index * colWidth) + 4f, y, textPaint)
        }
    }
}
